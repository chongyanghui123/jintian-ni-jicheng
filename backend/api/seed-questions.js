function main() {
  if (QUESTIONS.length !== 100) throw new Error(`题目数量 ${QUESTIONS.length} != 100`)
  const errors = []
  QUESTIONS.forEach(([t, a, b], i) => {
    if (!(t.length >= 4 && t.length <= 40)) errors.push(`#${i + 1} 题干长度 ${t.length}`)
    if (!(a.length >= 1 && a.length <= 16)) errors.push(`#${i + 1} 选项A长度 ${a.length}`)
    if (!(b.length >= 1 && b.length <= 16)) errors.push(`#${i + 1} 选项B长度 ${b.length}`)
    if (a === b) errors.push(`#${i + 1} 两选项相同`)
  })
  if (errors.length) {
    console.error('校验失败:\n' + errors.join('\n'))
    process.exit(1)
  }
  const ins = db.prepare(
    "INSERT OR IGNORE INTO questions (id, title, optionA, optionB, status) VALUES (?,?,?,?, 'draft')")
  let added = 0
  QUESTIONS.forEach(([t, a, b], i) => {
    const r = ins.run(`q${101 + i}`, t, a, b)
    added += r.changes
  })
  const total = db.prepare('SELECT COUNT(*) c FROM questions').get().c
  console.log(`新增 ${added} 道题（q101~q200，状态 draft）`)
  console.log(`题库总数：${total} 道；后台「排期 → 一键填充」可批量安排上墙`)
  db.close()
}

main()
